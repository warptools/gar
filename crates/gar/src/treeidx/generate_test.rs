use std::fs;
use std::os::unix::ffi::OsStrExt as _;
use std::os::unix::fs::PermissionsExt as _;
use std::path::Path;

use super::testutil::{ALPHA_ROOT, alpha_golden, alpha_tree, hash, scratch};
use super::{GenerateError, Kind, parse, serialize, verify};

/// The serializer's exact output, pinned: the alpha tree must index to the hand-written golden bytes.
#[test]
fn alpha_generates_the_golden_bytes() {
	let idx = generate_ok(&alpha_tree());
	assert_eq!(idx.root_hash(), &hash(ALPHA_ROOT));
	assert_eq!(
		String::from_utf8_lossy(&serialize(&idx)),
		String::from_utf8_lossy(&alpha_golden())
	);
}

/// The index of an empty tree is the header and the root line, with git's empty tree hash.
#[test]
fn empty_tree() {
	let td = scratch("treeidx-empty");
	let idx = generate_ok(td.path());
	assert_eq!(
		serialize(&idx),
		b"treeidx v1\n    2 ./ 040000 - 6ef19b41225c5369f1c104d45d8d85efa9b057b53b14b4b9b939dd74decc5321\n"
	);
	round_trip(td.path());
}

/// Filenames and symlink targets with spaces and newlines are what the length prefixes exist for.
/// Alongside: a non-UTF-8 name, the gitwise-order trap (file `foo.` before dir `foo`),
/// an executable, and empty directories, nested and not.
#[test]
fn nasty_names() {
	let td = scratch("treeidx-nasty");
	let root = td.path();
	fs::write(root.join("has space"), b"spaced\n").expect("write");
	fs::write(root.join("new\nline"), b"newlined\n").expect("write");
	fs::write(
		root.join(std::ffi::OsStr::from_bytes(b"not utf8 \xff\xfe")),
		b"bytes\n",
	)
	.expect("write");
	fs::write(root.join("foo."), b"dot\n").expect("write");
	fs::create_dir_all(root.join("foo/dir with space/empty")).expect("mkdir");
	fs::write(root.join("foo/dir with space/nested\nnewline"), b"deep\n").expect("write");
	fs::write(root.join("run.sh"), b"#!/bin/sh\n").expect("write");
	fs::set_permissions(root.join("run.sh"), fs::Permissions::from_mode(0o755)).expect("chmod");
	fs::create_dir(root.join("empty")).expect("mkdir");
	std::os::unix::fs::symlink("a target\nwith a newline", root.join("link")).expect("symlink");
	std::os::unix::fs::symlink("/absolute/elsewhere", root.join("abs link")).expect("symlink");

	let idx = round_trip(root);

	// Make sure the tree really exercised what it's meant to.
	let paths: Vec<&[u8]> = idx.entries().iter().map(|e| e.path.as_slice()).collect();
	let pos = |p: &[u8]| paths.iter().position(|q| *q == p).expect("path is indexed");
	assert!(
		pos(b"foo.") < pos(b"foo"),
		"gitwise order puts file foo. before dir foo"
	);
	assert!(paths.contains(&&b"foo/dir with space/nested\nnewline"[..]));
	assert!(paths.contains(&&b"not utf8 \xff\xfe"[..]));
	assert!(idx.entries().iter().any(|e| matches!(
		e.kind,
		Kind::File {
			executable: true,
			..
		}
	)));
	assert!(idx.entries().iter().any(|e| e.kind
		== Kind::Symlink {
			target: b"a target\nwith a newline".to_vec()
		}));
}

/// Materialized trees hold only files, dirs, and symlinks; anything else is an error, not a skip.
#[test]
fn unsupported_file_type_is_an_error() {
	let td = scratch("treeidx-socket");
	fs::write(td.path().join("a_file"), b"a file\n").expect("write");
	let _listener =
		std::os::unix::net::UnixListener::bind(td.path().join("sock")).expect("bind a socket");
	match super::generate(td.path()) {
		Err(GenerateError::Io(e)) => assert_eq!(e.kind(), std::io::ErrorKind::InvalidData),
		other => panic!("expected an InvalidData error, got {other:?}"),
	}
}

fn generate_ok(path: &Path) -> super::TreeIdx {
	super::generate(path).unwrap_or_else(|e| panic!("generating an index of {path:?}: {e}"))
}

/// Takes a tree on disk all the way around, checking every agreement along the way:
/// generate, serialize, parse, and re-verify, with every root hash equal to `gittree::hash_of_path`'s.
fn round_trip(path: &Path) -> super::TreeIdx {
	let want = gittree::hash_of_path(path).expect("hash_of_path");
	let idx = generate_ok(path);
	assert_eq!(idx.root_hash(), &want, "generated root vs hash_of_path");

	let bytes = serialize(&idx);
	let parsed = parse(&bytes).unwrap_or_else(|r| panic!("parsing generated bytes: {r}"));
	assert_eq!(parsed, idx, "parse should invert serialize");
	assert_eq!(
		serialize(&parsed),
		bytes,
		"re-serializing should be byte-identical"
	);

	let reverified = verify(parsed.into_entries()).expect("parsed entries re-verify");
	assert_eq!(
		reverified.root_hash(),
		&want,
		"arithmetic root vs hash_of_path"
	);
	idx
}
